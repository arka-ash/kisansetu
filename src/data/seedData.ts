// Helper: Haversine distance in km
export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) * Math.cos(lat2 * (Math.PI / 180)) *
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const d = R * c;
  return Math.round(d * 10) / 10;
}

// Helper: Realistic Indian Agri Freight Cost Estimation
export function calculateTransportCost(distanceKm: number, quantityKg: number): {
  cost: number;
  vehicleType: string;
  ratePerKm: number;
  estimatedDays: string;
} {
  let vehicleType = 'Tata Ace / Small Pickup (1 MT)';
  let ratePerKm = 14;
  let baseFixed = 400;

  if (quantityKg > 5000) {
    vehicleType = '10-Wheel Heavy Truck (10 MT)';
    ratePerKm = 32;
    baseFixed = 1600;
  } else if (quantityKg > 1500) {
    vehicleType = 'Tata 407 / Medium Truck (3.5 MT)';
    ratePerKm = 22;
    baseFixed = 850;
  }

  // Cost calculation with minimum threshold
  const distance = Math.max(distanceKm, 5);
  const rawCost = baseFixed + (distance * ratePerKm);
  const roundedCost = Math.round(rawCost / 50) * 50;

  let estimatedDays = '< 6 hours (Same Day)';
  if (distanceKm > 400) {
    estimatedDays = '2-3 Days';
  } else if (distanceKm > 100) {
    estimatedDays = '1 Day';
  }

  return {
    cost: roundedCost,
    vehicleType,
    ratePerKm,
    estimatedDays,
  };
}

// Quality compatibility check
export function isGradeCompatible(farmerGrade: QualityGrade, buyerMinGrade: QualityGrade): boolean {
  const gradeRank: Record<QualityGrade, number> = {
    'Grade C': 1,
    'Grade B': 2,
    'Grade A': 3,
    'Organic / Premium': 4,
  };
  return gradeRank[farmerGrade] >= gradeRank[buyerMinGrade];
}

